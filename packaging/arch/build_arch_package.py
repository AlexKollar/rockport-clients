#!/usr/bin/env python3
"""Assemble the Arch/Omarchy package (.pkg.tar.zst) for the
Rockport client from the release AppImage — the same payload
pattern as packaging/arch/PKGBUILD: the AppImage ships whole
under /usr/lib/rockport-client, a /usr/bin name points at it,
and pacman owns the install. Updates on this line arrive as
new packages (the client's updater learns to say exactly that
in v1.0.4; see src/main.rs).

Usage: build_arch_package.py <version> <appimage> <outdir>
Needs: python3 with zstandard (a venv is fine).
"""
import io
import os
import sys
import tarfile
import time

import zstandard

HERE = os.path.dirname(os.path.abspath(__file__))
CLIENT = os.path.dirname(os.path.dirname(HERE))  # the client tree

DESKTOP = """[Desktop Entry]
Type=Application
Name=Rockport
Comment=A Nocturne Row world — the standalone client
Exec=rockport-client
Icon=rockport-client
Terminal=false
Categories=Game;
"""


def pkginfo(version, size, builddate):
    lines = [
        "# Generated by build_arch_package.py — the PKGBUILD in "
        "packaging/arch is the source of record",
        "pkgname = rockport-client",
        "pkgbase = rockport-client",
        "pkgver = %s-1" % version,
        "pkgdesc = Rockport — a Nocturne Row world (standalone client)",
        "url = https://rockport.nocturnerow.com:4043",
        "builddate = %d" % builddate,
        "packager = Nocturne Row",
        "size = %d" % size,
        "arch = x86_64",
        "license = AGPL-3.0-or-later",
        "depend = webkit2gtk-4.1",
        "depend = gtk3",
    ]
    return ("\n".join(lines) + "\n").encode()


def add_bytes(tf, name, data, mode):
    info = tarfile.TarInfo(name)
    info.size = len(data)
    info.mode = mode
    info.mtime = int(time.time())
    tf.addfile(info, io.BytesIO(data))


def main():
    version, appimage, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(appimage, "rb") as fh:
        payload = fh.read()
    icon128 = open(os.path.join(CLIENT, "icons", "128x128.png"), "rb").read()
    icon32 = open(os.path.join(CLIENT, "icons", "32x32.png"), "rb").read()
    total = len(payload) + len(icon128) + len(icon32) + len(DESKTOP)
    os.makedirs(outdir, exist_ok=True)
    out = os.path.join(
        outdir, "rockport-client-%s-1-x86_64.pkg.tar.zst" % version)
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w") as tf:
        add_bytes(tf, ".PKGINFO", pkginfo(version, total, int(time.time())), 0o644)
        add_bytes(tf, "usr/lib/rockport-client/Rockport.AppImage",
                  payload, 0o755)
        link = tarfile.TarInfo("usr/bin/rockport-client")
        link.type = tarfile.SYMTYPE
        link.linkname = "../lib/rockport-client/Rockport.AppImage"
        link.mode = 0o777
        link.mtime = int(time.time())
        tf.addfile(link)
        add_bytes(tf, "usr/share/applications/rockport-client.desktop",
                  DESKTOP.encode(), 0o644)
        add_bytes(tf, "usr/share/icons/hicolor/128x128/apps/rockport-client.png",
                  icon128, 0o644)
        add_bytes(tf, "usr/share/icons/hicolor/32x32/apps/rockport-client.png",
                  icon32, 0o644)
    cctx = zstandard.ZstdCompressor(level=19)
    with open(out, "wb") as fh:
        fh.write(cctx.compress(buf.getvalue()))
    print("WROTE", out, os.path.getsize(out))


if __name__ == "__main__":
    main()
